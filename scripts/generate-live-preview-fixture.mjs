import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const outputPath = resolve(
  scriptDir,
  "../src/__tests__/fixtures/md/live-preview-100k.md",
);

let seed = 0x20260729;
function random() {
  seed ^= seed << 13;
  seed ^= seed >>> 17;
  seed ^= seed << 5;
  return (seed >>> 0) / 0x1_0000_0000;
}

const chinese = [
  "编辑器需要在光标所在行恢复原始标记，其余内容保持清晰可读。",
  "文件内容始终是唯一事实源，渲染装饰不能进入撤销历史。",
  "中英文混排用于覆盖实际文档中的排版、选择和输入行为。",
];
const english = [
  "Live Preview keeps the Markdown source lossless while presenting inactive blocks.",
  "Viewport-bounded decorations keep long documents responsive during scrolling.",
  "Autosave, undo, and external file conflict handling remain independent of rendering.",
];

const parts = [
  "# CodePilot Live Preview 100K Fixture",
  "",
  "> Generated by `scripts/generate-live-preview-fixture.mjs` with seed `0x20260729`.",
  "",
];

for (let section = 1; section <= 200; section += 1) {
  parts.push(
    `## Section ${section}: **Live Preview** 与 \`source-${section}\``,
    "",
    `${chinese[Math.floor(random() * chinese.length)]} ${english[Math.floor(random() * english.length)]}`,
    "",
    `- item ${section}.1 with [CodePilot](https://example.com/${section})`,
    `- item ${section}.2 includes inline math $x_${section} + y_${section}$`,
    "",
  );

  if (section % 4 === 0) {
    parts.push(
      "```ts",
      `export function section${section}(value: number) {`,
      ...Array.from(
        { length: 12 + (section % 9) },
        (_, line) =>
          `  const value${line} = value + ${line}; // deterministic viewport load`,
      ),
      `  return value${section % 9};`,
      "}",
      "```",
      "",
    );
  }

  if (section % 10 === 0) {
    parts.push(
      "| Type | Status | Section |",
      "| --- | --- | ---: |",
      `| Markdown | Ready | ${section} |`,
      `| Table | Rendered | ${section} |`,
      "",
    );
  }

  if (section % 25 === 0) {
    parts.push(
      "$$",
      `\\sum_{i=1}^{${section}} i = \\frac{${section}(${section}+1)}{2}`,
      "$$",
      "",
    );
  }
}

while (parts.join("\n").length < 100_000) {
  const index = parts.length;
  parts.push(
    `补充段落 ${index}：${chinese[index % chinese.length]} ${english[index % english.length]}`,
    "",
  );
}

await mkdir(dirname(outputPath), { recursive: true });
const output = `${parts.join("\n").trimEnd()}\n`;
await writeFile(outputPath, output, "utf8");

console.log(`generated ${outputPath} (${output.length} chars)`);

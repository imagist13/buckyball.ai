import {
  copyFile,
  mkdir,
  readFile,
  readdir,
  unlink,
  writeFile,
} from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const GENERATOR_VERSION = 1;
const scriptDir = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDir, "..");
const packageRoot = resolve(projectRoot, "node_modules/material-icon-theme");
const packageJson = JSON.parse(
  await readFile(resolve(packageRoot, "package.json"), "utf8"),
);
const theme = JSON.parse(
  await readFile(resolve(packageRoot, "dist/material-icons.json"), "utf8"),
);

const specialNames = [
  "package.json",
  "tsconfig.json",
  "jsconfig.json",
  "Dockerfile",
  "docker-compose.yml",
  "docker-compose.yaml",
  "Makefile",
  ".gitignore",
  ".gitattributes",
  ".env",
  ".env.local",
  "README.md",
  "CHANGELOG.md",
  "LICENSE",
  "pnpm-lock.yaml",
  "package-lock.json",
  "yarn.lock",
  "vite.config.ts",
  "next.config.ts",
];

const compoundSuffixes = {
  ".d.ts": "typescript-def",
  ".test.ts": "test-ts",
  ".spec.ts": "test-ts",
  ".test.tsx": "test-ts",
  ".spec.tsx": "test-ts",
  ".test.js": "test-js",
  ".spec.js": "test-js",
  ".test.jsx": "test-jsx",
  ".spec.jsx": "test-jsx",
};

const extensions = [
  "md", "mdx", "txt", "ts", "tsx", "js", "jsx", "json", "jsonc",
  "yaml", "yml", "toml", "html", "htm", "css", "scss", "sass", "less",
  "py", "rs", "go", "java", "dart", "vue", "svelte", "astro", "sql",
  "sh", "bash", "zsh", "ps1", "csv", "tsv", "svg", "png", "jpg", "jpeg",
  "gif", "webp", "pdf", "zip", "gz", "lock",
];

const fallbackByExtension = {
  mdx: "markdown",
  txt: "document",
  htm: "html",
  bash: "console",
  zsh: "console",
  ps1: "powershell",
  jpg: "image",
  jpeg: "image",
  gif: "image",
  webp: "image",
  gz: "zip",
  lock: "lock",
};

const resolveNameIcon = (name) =>
  theme.fileNames[name] ??
  theme.fileNames[name.toLowerCase()] ??
  (name.startsWith(".env") ? "tune" : "file");
const specialNameIcons = Object.fromEntries(
  specialNames.map((name) => [name.toLowerCase(), resolveNameIcon(name)]),
);
const extensionIcons = Object.fromEntries(
  extensions.map((extension) => [
    extension,
    theme.fileExtensions[extension] ?? fallbackByExtension[extension] ?? "file",
  ]),
);
const iconIds = [
  ...new Set([
    "file",
    ...Object.values(specialNameIcons),
    ...Object.values(compoundSuffixes),
    ...Object.values(extensionIcons),
  ]),
].sort();

const publicDir = resolve(projectRoot, "public/file-type-icons");
const metadataDir = resolve(projectRoot, "src/components/ui/file-type-icons");
await mkdir(publicDir, { recursive: true });
await mkdir(metadataDir, { recursive: true });

for (const existing of await readdir(publicDir)) {
  if (
    existing.endsWith(".svg") &&
    !iconIds.includes(existing.slice(0, -4))
  ) {
    await unlink(resolve(publicDir, existing));
  }
}

for (const iconId of iconIds) {
  const definition = theme.iconDefinitions[iconId];
  if (!definition?.iconPath) {
    throw new Error(`material-icon-theme has no icon definition for ${iconId}`);
  }
  const source = resolve(packageRoot, "dist", definition.iconPath);
  await copyFile(source, resolve(publicDir, `${iconId}.svg`));
}

const generated = `// Generated by scripts/generate-file-type-icons.mjs. Do not edit by hand.
export const GENERATED_FILE_ICON_PATHS = ${JSON.stringify(
  Object.fromEntries(iconIds.map((id) => [id, `/file-type-icons/${id}.svg`])),
  null,
  2,
)} as const;

export const GENERATED_SPECIAL_NAME_ICONS = ${JSON.stringify(specialNameIcons, null, 2)} as const;
export const GENERATED_COMPOUND_SUFFIX_ICONS = ${JSON.stringify(compoundSuffixes, null, 2)} as const;
export const GENERATED_EXTENSION_ICONS = ${JSON.stringify(extensionIcons, null, 2)} as const;

export type GeneratedFileIconId = keyof typeof GENERATED_FILE_ICON_PATHS;
`;
await writeFile(
  resolve(projectRoot, "src/components/ui/file-type-icons.generated.ts"),
  generated,
  "utf8",
);

const repository =
  typeof packageJson.repository === "string"
    ? packageJson.repository
    : packageJson.repository?.url;
const upstreamRepository = String(repository)
  .replace(/^git\+/, "")
  .replace(/\.git$/, "");
const manifest = {
  generatedBy: "scripts/generate-file-type-icons.mjs",
  generatorVersion: GENERATOR_VERSION,
  sourcePackage: "material-icon-theme",
  sourceVersion: packageJson.version,
  upstreamRepository,
  license: "MIT",
  trademarkNotice:
    "Third-party brand marks remain subject to their owners' trademark terms. They are used only to identify file types and do not imply endorsement.",
  icons: iconIds.map((iconId) => ({
    iconId,
    sourceFile: theme.iconDefinitions[iconId].iconPath
      .replace(/^\.\.\/icons\//, "icons/")
      .replace(/^\.\/\.\.\/icons\//, "icons/"),
    outputFile: `public/file-type-icons/${iconId}.svg`,
    sourcePackage: "material-icon-theme",
    sourceVersion: packageJson.version,
    upstreamRepository,
    license: "MIT",
  })),
};
await writeFile(
  resolve(metadataDir, "file-type-icons.manifest.json"),
  `${JSON.stringify(manifest, null, 2)}\n`,
  "utf8",
);
await copyFile(
  resolve(packageRoot, "LICENSE"),
  resolve(metadataDir, "LICENSE.material-icon-theme"),
);

console.log(
  `generated ${iconIds.length} file icons from material-icon-theme ${packageJson.version}`,
);
